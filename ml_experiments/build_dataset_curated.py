def main():
    rows = []
    for query, chunk in POSITIVE:
        rows.append(
            {
                "query": query,
                "chunk": chunk,
                "chunk_length": len(chunk),
                "query_length": len(query),
                "num_legal_terms": sum(
                    chunk.lower().count(t)
                    for t in ["статья", "пункт", "кодекс", "закон"]
                ),
                "has_article_number": int(
                    "статья" in chunk.lower() and any(c.isdigit() for c in chunk)
                ),
                "rank": 0,
                "relevant": 1,
            }
        )
    for query, chunk in NEGATIVE:
        rows.append(
            {
                "query": query,
                "chunk": chunk,
                "chunk_length": len(chunk),
                "query_length": len(query),
                "num_legal_terms": sum(
                    chunk.lower().count(t)
                    for t in ["статья", "пункт", "кодекс", "закон"]
                ),
                "has_article_number": int(
                    "статья" in chunk.lower() and any(c.isdigit() for c in chunk)
                ),
                "rank": 0,
                "relevant": 0,
            }
        )

    random.seed(42)
    random.shuffle(rows)

    with open("ml_experiments/dataset.csv", "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=rows[0].keys())
        writer.writeheader()
        writer.writerows(rows)

    print(f"Сохранено {len(rows)} строк в ml_experiments/dataset.csv")
    print(
        f"Положительных: {sum(r['relevant'] for r in rows)}, отрицательных: {len(rows) - sum(r['relevant'] for r in rows)}"
    )


if __name__ == "__main__":
    main()
