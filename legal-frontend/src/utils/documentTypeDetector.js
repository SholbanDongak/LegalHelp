// Утилита для автоматического определения типа документа на основе текста
export function detectDocumentType(text) {
  const lowerText = text.toLowerCase();
  
  // Паттерны для определения типа документа
  const patterns = {
    'claim_consumer': [
      /вернуть.*товар|некачественн.*товар|потребител|купил.*сломал|магазин.*вернуть/i,
      /защит.*прав.*потребител|брак.*товар|неисправн/i
    ],
    'claim_labor_wage': [
      /зарплат|жалованье|не плат.*работ|задержк.*выплат|работодат.*долж/i,
      /взыск.*зарплат|трудов.*спор.*оплат/i
    ],
    'claim_labor_reinstatement': [
      /увол.*незаконн|восстанов.*работ|уволил.*без причин|неправ.*увольн/i
    ],
    'claim_divorce': [
      /развод|расторж.*брак|развест.*муж|развест.*жен/i
    ],
    'claim_alimony': [
      /алименты|содержан.*ребенок|взыск.*алимент/i
    ],
    'claim_civil_general': [
      /долг.*вернуть|занял.*деньги|не возвращ.*деньг|расписк|договор.*займ/i,
      /взыск.*денеж|имуществ.*спор/i
    ],
    'admin_claim_kas': [
      /орган.*власт|чиновник|бездействи|незаконн.*решен.*орган|административ.*иск/i,
      /обжал.*действи.*должностн|отказ.*государствен/i
    ],
    'complaint_koap': [
      /постановлен.*коап|штраф.*гибдд|административ.*правонаруш|протокол/i
    ],
    'application_for_court_order': [
      /судебн.*приказ|бесспорн.*взыскани|прост.*долг/i
    ],
    'objection_to_court_order': [
      /возражен.*судебн.*приказ|отмен.*приказ.*миров/i
    ],
    'special_proceeding_fact': [
      /установ.*факт|юридическ.*значен|родствен.*отношен|иждивен|принадлеж.*документ/i
    ],
    'appeal_civil': [
      /апелляц.*жалоб|обжал.*решен.*суд|несоглас.*решен/i
    ],
    'cassation_civil': [
      /кассац.*жалоб|нарушен.*норм.*прав|судеб.*акт.*вступ.*сил/i
    ]
  };
  
  // Проверяем каждый тип
  for (const [docType, regexArray] of Object.entries(patterns)) {
    for (const regex of regexArray) {
      if (regex.test(lowerText)) {
        return {
          docType,
          confidence: 0.7,
          reason: 'Автоматическое определение по ключевым словам'
        };
      }
    }
  }
  
  // Если ничего не найдено — возвращаем общий иск как fallback
  return {
    docType: 'claim_civil_general',
    confidence: 0.3,
    reason: 'Не удалось определить тип автоматически, предложен общий иск'
  };
}
