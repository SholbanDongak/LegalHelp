"""
LLM-классификатор правовых ситуаций.
Использует LLaMA 3.1:8b для понимания смысла запроса.
"""
import json
import re
from typing import Dict, Optional
from ollama import AsyncClient
import asyncio


# Промпт для LLM — чёткие инструкции + список типов
CLASSIFICATION_PROMPT = """Ты — эксперт-юрист, который определяет тип юридического документа по запросу гражданина.

ВАЖНО: Граждане пишут простым разговорным языком. Ты должен понять СУТЬ проблемы, а не ключевые слова.

ПРИМЕРЫ:
- "мне денег не дали работал месяц" → Иск о взыскании заработной платы
- "сосед занял и не отдает" → Исковое заявление (общее)
- "телефон сломался хочу вернуть" → Иск о защите прав потребителей
- "меня выгнали с работы" → Иск о восстановлении на работе
- "муж не дает деньги на ребенка" → Иск о взыскании алиментов
- "хочу развестись" → Иск о расторжении брака
- "в мэрии отказали в справке" → Административное исковое заявление
- "пенсионный фонд не дает пенсию" → Административное исковое заявление (ПФР — госорган)
- "обманули в пенсионном" → Административное исковое заявление
- "ФСС не выплатил пособие" → Административное исковое заявление (ФСС — госорган)
- "судебные приставы бездействуют" → Административное исковое заявление
- "штраф гибдд хочу обжаловать" → Жалоба на постановление по КоАП
- "нужно доказать что мы родственники" → Заявление об установлении факта
- "не согласен с решением суда" → Апелляционная жалоба

ДОСТУПНЫЕ ТИПЫ ДОКУМЕНТОВ:
1. claim_consumer — Иск о защите прав потребителей (возврат товара, некачественная услуга)
2. claim_labor_wage — Иск о взыскании зарплаты (не платят зарплату, задержка)
3. claim_labor_reinstatement — Иск о восстановлении на работе (незаконное увольнение)
4. claim_divorce — Иск о расторжении брака (развод)
5. claim_alimony — Иск о взыскании алиментов (не платят на детей)
6. claim_civil_general — Исковое заявление общее (долги, займы, расписки)
7. admin_claim_kas — Административное исковое заявление (отказ госорганов, чиновники)
8. complaint_koap — Жалоба на постановление по КоАП (штрафы ГИБДД, административные дела)
9. application_for_court_order — Заявление о судебном приказе (бесспорные долги)
10. objection_to_court_order — Возражение на судебный приказ
11. appeal_civil — Апелляционная жалоба (не согласен с решением суда первой инстанции)
12. cassation_civil — Кассационная жалоба (нарушение норм права)
13. special_proceeding_fact — Заявление об установлении факта (родство, наследство и т.п.)
14. unknown — Не удалось определить

ЗАДАЧА:
Проанализируй запрос пользователя и определи ТИП ДОКУМЕНТА.

ОТВЕТЬ СТРОГО В ФОРМАТЕ JSON (без markdown, без пояснений):
{"type": "claim_type", "confidence": 0.95, "reason": "краткое обоснование"}

Где:
- type — один из типов выше
- confidence — уверенность от 0.0 до 1.0
- reason — почему выбран этот тип (1 предложение)
"""


async def classify_with_llm_async(query: str) -> Dict:
    """
    Асинхронная классификация через LLaMA.
    
    Returns:
        {
            'type': 'claim_type',
            'confidence': 0.95,
            'reason': 'обоснование'
        }
    """
    client = AsyncClient(host='http://127.0.0.1:11434')
    
    try:
        response = await client.chat(
            model='llama3.1:8b',
            messages=[
                {"role": "system", "content": CLASSIFICATION_PROMPT},
                {"role": "user", "content": f"Запрос пользователя: {query}"}
            ],
            options={
                'temperature': 0.1,  # Минимальная случайность
                'top_p': 0.9,
                'num_predict': 200
            }
        )
        
        answer = response['message']['content'].strip()
        
        # Извлекаем JSON из ответа
        json_match = re.search(r'\{[^}]+\}', answer)
        if json_match:
            result = json.loads(json_match.group())
            return {
                'type': result.get('type', 'unknown'),
                'confidence': float(result.get('confidence', 0.5)),
                'reason': result.get('reason', 'LLM классификация')
            }
        else:
            return {
                'type': 'unknown',
                'confidence': 0.0,
                'reason': f'LLM не вернул JSON: {answer[:100]}'
            }
            
    except Exception as e:
        return {
            'type': 'unknown',
            'confidence': 0.0,
            'reason': f'Ошибка LLM: {str(e)}'
        }


def classify_with_llm(query: str) -> Dict:
    """Синхронная обёртка для classify_with_llm_async."""
    try:
        loop = asyncio.get_event_loop()
        if loop.is_running():
            # Если уже в event loop — используем run_coroutine_threadsafe
            import concurrent.futures
            with concurrent.futures.ThreadPoolExecutor() as pool:
                future = pool.submit(asyncio.run, classify_with_llm_async(query))
                return future.result()
        else:
            return asyncio.run(classify_with_llm_async(query))
    except RuntimeError:
        return asyncio.run(classify_with_llm_async(query))


